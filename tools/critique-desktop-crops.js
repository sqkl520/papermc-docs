/* critique-desktop-crops.js — crop evidence regions from ui-shots PNGs, re-encode as JPEG,
 * emit markdown data-URI images so reports/critique-desktop.md can be opened standalone.
 * Usage: node tools/critique-desktop-crops.js
 * Writes reports/_critique-desktop-crops.md (fragment, appended by hand into the report)
 */
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright-core');

const ROOT = path.resolve(__dirname, '..');
const SHOTS = path.join(ROOT, 'reports', 'ui-shots');
const OUT = path.join(ROOT, 'reports', '_critique-desktop-crops.md');
const OUTDIR = path.join(ROOT, 'reports', 'critique-desktop-evidence');
const EXE = [process.env.CHROME_PATH,
process.env.LOCALAPPDATA && path.join(process.env.LOCALAPPDATA, 'ms-playwright', 'chromium-1234', 'chrome-win', 'chrome.exe'),
process.env.PROGRAMFILES && path.join(process.env.PROGRAMFILES, 'Google', 'Chrome', 'Application', 'chrome.exe')].filter(Boolean).find(p => fs.existsSync(p));

/* crops are in device pixels of the 2x screenshot: x = css*2 */
const CROPS = [
  { id: 'E1-topbar', file: '1440x900/content-callout-code.fold.png', css: [0, 0, 1440, 52], cap: 'E1 顶栏 1440x52（含 查看原文↗ / 页面源 Markdown / 搜索 Ctrl+K / 跟随系统 + 三分区切换）' },
  { id: 'E2-head-chips', file: '1440x900/content-callout-code.fold.png', css: [290, 62, 1150, 250], cap: 'E2 正文列顶部：面包屑→H1→描述→4 chips+查看原文（同一屏第二次「查看原文」）' },
  { id: 'E3-toc-24', file: '1440x900/content-callout-code.fold.png', css: [1180, 52, 260, 560], cap: 'E3 右栏本页目录 24 项 / 250px，全部同缩进 6.4px' },
  { id: 'E4-sidebar', file: '1440x900/content-callout-code.fold.png', css: [0, 52, 290, 848], cap: 'E4 左栏 290px：过滤框 + 「主导航=…」图例 + 190+ 链接 / 多色徽章' },
  { id: 'E5-images-shift', file: '1440x900/content-callout-code.fold.png', css: [300, 460, 900, 440], cap: 'E5 lazy 图片无 width/height：加载前占位 2x2，加载后撑到 849x478（CLS 0.08 / 文档高 13737→14034）' },
  { id: 'E6-codeblock', file: '1440x900/reference-longpage.fold.png', css: [300, 660, 980, 240], cap: 'E6 代码块：仅语言标签 YAML + 复制按钮（39.4x21.2），无行号 / 无行高亮 / 无横滚提示' },
  { id: 'E7-allpages-table', file: '1440x900/index-allpages.fold.png', css: [290, 380, 1150, 900], cap: 'E7 all-pages 141 行 × 6 列，行高 62px，序号列仅 44px 宽，表头非 sticky' },
  { id: 'E8-surrounding-space', file: '1440x900/content-callout-code.fold.png', css: [1130, 52, 310, 848], cap: 'E8 正文右边缘 1164 → 视口 1440：276px 侧边留白（TOC 只占 250px）' },
  { id: 'E9-1280', file: '1280x800/content-callout-code.fold.png', css: [0, 0, 1280, 800], cap: 'E9 1280x800：article 掉到 689px / 98.7ch，右栏 250px 仍在' },
];

(async () => {
  fs.mkdirSync(OUTDIR, { recursive: true });
  const browser = await chromium.launch({ executablePath: EXE, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const ctx = await browser.newContext({ viewport: { width: 600, height: 400 }, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  const parts = ['<!-- generated by tools/critique-desktop-crops.js -->'];
  for (const c of CROPS) {
    const src = fs.readFileSync(path.join(SHOTS, c.file)).toString('base64');
    const [x, y, w, h] = c.css;
    const jpeg = await page.evaluate(async ({ src, x, y, w, h }) => {
      const im = new Image();
      im.src = 'data:image/png;base64,' + src;
      await im.decode();
      const s = 2; // screenshots are 2x
      const cv = document.createElement('canvas');
      // cap output width at 1600 css px worth for file size
      const scale = Math.min(1, 1600 / (w * s));
      cv.width = Math.round(w * s * scale);
      cv.height = Math.round(h * s * scale);
      const g = cv.getContext('2d');
      g.imageSmoothingEnabled = true;
      g.imageSmoothingQuality = 'high';
      g.fillStyle = '#fff'; g.fillRect(0, 0, cv.width, cv.height);
      g.drawImage(im, x * s, y * s, w * s, h * s, 0, 0, cv.width, cv.height);
      return cv.toDataURL('image/jpeg', 0.82);
    }, { src, x, y, w, h });
    const b64 = jpeg.split(',')[1];
    const buf = Buffer.from(b64, 'base64');
    const fname = c.id + '.jpg';
    fs.writeFileSync(path.join(OUTDIR, fname), buf);
    parts.push('\n### ' + c.id + '\n\n' + c.cap + '\n\n![`' + c.id + '`](critique-desktop-evidence/' + fname + ')\n\n<details><summary>data-URI 内嵌（单文件离线可读）</summary>\n\n![`' + c.id + '`](' + jpeg + ')\n\n</details>\n');
    console.log(c.id, fname, Math.round(buf.length / 1024) + 'KB');
  }
  fs.writeFileSync(OUT, parts.join('\n'), 'utf8');
  console.log('wrote', OUT);
  await browser.close();
})().catch(e => { console.error('ERR', e && e.stack || e); process.exit(1); });
